#!/usr/bin/env python3
"""Generate Source/SymphonyMixerCoef.h: the card mixer's 16-bit coefficients
as Apogee's driver computed them (og_source/maestrolink/Software/
SymphonyPCIeCardMixer.cpp:1263-1274, 1289-1318, 1364-1430). The dext has no
pow, sin or log, so it looks them up.

    coef(dB) = ((long)(pow(10, dB/20) / 4.0 * 0x8000) & 0xFFFF) << 16

Rows: the sum of fader and Master in whole dB, from kRowMin to kRowMax.
Columns: the pan term for pan byte p (0...128): 20*log10(sin(p/128 * pi/2)),
the original's equal-power law (p = 128 is 0 dB, p = 0 is off). The left
side of a strip uses column 128 - p, the right side column p, and the
Software Return (no pan) column 128.

The original adds fader, pan term and Master in that order in float; a table
indexed by (fader + Master) adds them in another order. `--check` evaluates
the original's order for every fader, Master and pan and reports how many
entries differ and by how much.
"""
import math, struct, sys

ROW_MIN, ROW_MAX = -96, 12   # fader + Master, whole dB (fader and Master are -47...+6)

def f32(x):
    return struct.unpack('f', struct.pack('f', x))[0]

def coef16(db):
    if db == -math.inf: return 0
    lin = math.pow(10.0, db / 20.0)
    l = int(lin / 4.0 * 0x8000)           # C (long) truncates toward zero
    return l & 0xFFFF

def pan_term(p):
    # fpCrossfade = 0.5f + fpPan/2.0f with fpPan = p/64 - 1 (float), then
    # fpPanGain = (float)sin(fpCrossfade * M_PI/2.0) for the right side.
    pan = f32(p / 64.0 - 1.0)
    x = f32(0.5 + f32(pan / 2.0))
    g = f32(math.sin(x * math.pi / 2.0))
    return -math.inf if g <= 0.0 else 20.0 * math.log10(g)

PAN = [pan_term(p) for p in range(129)]

def table_value(row, p):
    t = PAN[p]
    if t == -math.inf: return 0
    return coef16(f32(row + t))

def original_value(fader, master, p):
    # fpChannelGain = fader; += 20*log10(panGain) (double, stored as float);
    # += master (float).
    t = PAN[p]
    if t == -math.inf: return 0
    g = f32(fader + t)
    g = f32(g + master)
    return coef16(g)

def main():
    if '--check' in sys.argv:
        diffs, worst = 0, 0
        for fader in range(-47, 7):
            for master in range(-47, 7):
                for p in range(129):
                    a = original_value(fader, master, p)
                    b = table_value(fader + master, p)
                    if a != b:
                        diffs += 1; worst = max(worst, abs(a - b))
        print('entries compared: %d, differing: %d, largest difference: %d' % (54 * 54 * 129, diffs, worst))
        sys.exit(0 if worst <= 1 else 1)
    rows = []
    for row in range(ROW_MIN, ROW_MAX + 1):
        vals = [table_value(row, p) for p in range(129)]
        assert max(vals) < 0x8000, 'coefficient would wrap into the sign bit'
        rows.append('    {' + ', '.join('0x%04x' % v for v in vals) + '},  // %+d dB' % row)
    out = [
        '// Generated by Drivers/Thunderbolt/Scripts/gen-mixer-coef.py. Do not edit.',
        '// The card mixer coefficients of Apogee\'s driver',
        '// (SymphonyPCIeCardMixer.cpp:1263-1274, 1364-1430): see the script.',
        '#pragma once',
        '#include <stdint.h>',
        '',
        'static constexpr int kSymphonyMixerCoefRowMin = %d;' % ROW_MIN,
        'static constexpr int kSymphonyMixerCoefRowMax = %d;' % ROW_MAX,
        '',
        '// [fader + Master dB - kSymphonyMixerCoefRowMin][pan column] -> top 16 bits.',
        'static const uint16_t kSymphonyMixerCoef[%d][129] = {' % (ROW_MAX - ROW_MIN + 1),
        *rows,
        '};',
        '',
        '// The register value for a sum in whole dB and a pan column; 0 (off)',
        '// below the table.',
        'static inline uint32_t SymphonyMixerCoef(int sumDb, unsigned column)',
        '{',
        '    if (sumDb < kSymphonyMixerCoefRowMin || column > 128) return 0;',
        '    if (sumDb > kSymphonyMixerCoefRowMax) sumDb = kSymphonyMixerCoefRowMax;',
        '    return (uint32_t)kSymphonyMixerCoef[sumDb - kSymphonyMixerCoefRowMin][column] << 16;',
        '}',
        '',
    ]
    open(sys.argv[1] if len(sys.argv) > 1 else 'Source/SymphonyMixerCoef.h', 'w').write('\n'.join(out))

main()
